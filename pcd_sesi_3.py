import imageio.v3 as iio
import numpy as np
import matplotlib.pyplot as plt

nama_file = 'plat1R.jpeg'
img_rgb = iio.imread(nama_file)

img_gray = np.dot(img_rgb[..., :3], [0.2989, 0.5870, 0.1140]).astype(np.uint8)

histogram, bin_edges = np.histogram(img_gray, bins=256, range=(0, 256))

print("--- Data Jumlah Piksel per Intensitas (Sebagian) ---")
for i in range(0, 256, 50): # Menampilkan sampel tiap kelipatan 50 agar rapi
    print(f"Intensitas {i}: {histogram[i]} piksel")
print(f"Intensitas 255: {histogram[255]} piksel\n")

intensitas_dominan = np.argmax(histogram)
jumlah_piksel_maks = histogram[intensitas_dominan]
print("--- Analisis Intensitas Dominan ---")
print(f"Intensitas paling dominan adalah {intensitas_dominan}")
print(f"Jumlah piksel pada intensitas dominan: {jumlah_piksel_maks} piksel")

plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.imshow(img_gray, cmap='gray')
plt.title('Gambar Grayscale')
plt.axis('off')

plt.subplot(1, 2, 2)
plt.plot(histogram, color='black')
plt.title('Histogram Citra Grayscale')
plt.xlabel('Nilai Intensitas Piksel (0-255)')
plt.ylabel('Total Frekuensi / Jumlah Piksel')
plt.xlim([0, 256])
plt.grid(axis='y', alpha=0.5, linestyle='--')

plt.tight_layout()
plt.show()